class House:
	def __init__(self, servis):
		self.rooms = {}
		self.servis = servis
		self.events = []
		self.max_room_count = 5
	def get_room(self, name):
		try:
			return self.rooms[name]
		except KeyError:
			return None
	def add_room(self, room):
		if len(self.rooms)+1<= self.max_room_count:
			room.house = self
			self.rooms.update({room.name:room})
		#self.events.append(["Add room", [room.name]])
	def remove_room(self, room):
		self.rooms.pop(room.name)
		#self.events.append(["Remove room", [room.name]])
	def tick(self):
		for room in list(self.rooms.values()):
			room.update()

