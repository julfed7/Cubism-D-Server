	def take_damage(self, damage, position):
		distance = math.sqrt((position[0]-self.position[0])**2+(position[1]-self.position[1])**2)
		if self.ticks-self.last_taked_damage>self.damage_resist_ticks and distance < DEFAULT_HIT_RANGE:
			self.hp -= damage
		self.last_taked_damage = self.ticks
	def update(self):
		self.rect.x = self.position[0]
		self.rect.y = self.position[1]
		self.move(self.velocity)
		self.ticks += 1
		if self.hp <= 0:
			self.room.remove_game_object(self)
		if self.ticks > self.live_time:
			self.hp = 0
